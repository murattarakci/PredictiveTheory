suppressMessages({ library(dplyr); library(sandwich); library(lmtest) })
src <- readLines("rerun_v2_corrected.R")
eval(parse(text = src[1:(grep("^# ---------------------------------------------------------------- main loop", src) - 1)]))
r <- read.csv("results_v2/results_v2_clustered.csv", stringsAsFactors = FALSE)
s <- r[r$dv == "mean_roa", ]; bt <- s[which.min(s$test_rmse), ]
m <- lm(as.formula(bt$formula), data = train_data)
rows <- as.integer(rownames(model.frame(m)))
ct <- coeftest(m, vcov = vcovCL(m, cluster = train_data$gvkey[rows], type = "HC1"))
keep <- !grepl("^factor\\(", rownames(ct))
sink("results_v2/best_model_table_v2.txt", split = TRUE)
cat(bt$formula, "\n"); print(round(ct[keep, ], 4))
sm <- summary(m)
cat("observations", nobs(m), "| firms", length(unique(train_data$gvkey[rows])), "| R2", round(sm$r.squared, 3), "| adj R2", round(sm$adj.r.squared, 3), "| RSE", round(sm$sigma, 3), "| df", sm$df[2], "\n")
cat("industry FE levels:", length(m$xlevels[["factor(sic_2)"]]), "| year FE levels:", length(m$xlevels[["factor(year)"]]), "\n")
cat("ME", round(bt$me_train, 3), "clustered SE", round(bt$se_train_cl, 3), "| ME on validation firms", round(bt$me_val, 3), "clustered SE", round(bt$se_val_cl, 3), "\n")
cat("test RMSE", round(bt$test_rmse, 3), "(n", bt$test_n, ") | val RMSE", round(bt$val_rmse, 3), "(n", bt$val_n, ") | val RMSE without CSP", round(bt$val_rmse_without_csp, 3), "\n")
cat("mean R&D in estimation sample:", round(mean(model.frame(m)$RD), 4), "\n")
sink()
